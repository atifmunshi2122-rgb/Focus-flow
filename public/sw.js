/**
 * FocusFlow Service Worker — Versioned App Shell & Safe Asset Cache
 * Implements content-type safe offline navigation and immutable asset caching.
 */

const SHELL_CACHE_NAME = 'focusflow-shell-v3';
const ASSETS_CACHE_NAME = 'focusflow-assets-v3';

const APP_SHELL_URLS = [
  '/',
  '/index.html',
  '/manifest.webmanifest',
  '/logo.png',
  '/icon-192.png',
  '/icon-512.png',
  '/apple-touch-icon.png',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(SHELL_CACHE_NAME)
      .then((cache) => cache.addAll(APP_SHELL_URLS))
      .catch((err) => {
        console.warn('[SW] Shell precache partial failure:', err);
      })
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  const currentCaches = new Set([SHELL_CACHE_NAME, ASSETS_CACHE_NAME]);
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((k) => k.startsWith('focusflow-') && !currentCaches.has(k))
            .map((k) => caches.delete(k))
        )
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;

  // Only intercept GET requests
  if (request.method !== 'GET') return;

  const url = new URL(request.url);

  // 1. Never intercept cross-origin requests (Firebase Auth, Cloud Firestore, Google Sheets API)
  if (url.origin !== self.location.origin) {
    return;
  }

  // 2. Never intercept backend API endpoints (/api/*) to avoid serving stale personal financial data
  if (url.pathname.startsWith('/api/')) {
    return;
  }

  // 3. Navigation Requests (HTML SPA Fallback)
  // When the user opens or reloads a route (e.g. /focus, /study, /finance)
  if (request.mode === 'navigate' || request.headers.get('accept')?.includes('text/html')) {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response && response.status === 200 && response.type === 'basic') {
            const clone = response.clone();
            caches.open(SHELL_CACHE_NAME).then((cache) => cache.put(request, clone)).catch(() => undefined);
          }
          return response;
        })
        .catch(async () => {
          const cachedNavigate = await caches.match(request);
          if (cachedNavigate) return cachedNavigate;
          const cachedIndex = await caches.match('/index.html');
          if (cachedIndex) return cachedIndex;
          return new Response('<h1>FocusFlow is Offline</h1><p>Please check your internet connection.</p>', {
            status: 503,
            headers: { 'Content-Type': 'text/html; charset=utf-8' },
          });
        })
    );
    return;
  }

  // 4. Hashed / Fingerprinted Static Assets (/assets/*)
  // Immutable chunks generated by Vite: Cache-first strategy for instant subsequent loads
  if (url.pathname.startsWith('/assets/')) {
    event.respondWith(
      caches.match(request).then((cachedResponse) => {
        if (cachedResponse) {
          return cachedResponse;
        }

        return fetch(request)
          .then((networkResponse) => {
            if (networkResponse && networkResponse.status === 200 && networkResponse.type === 'basic') {
              const clone = networkResponse.clone();
              caches.open(ASSETS_CACHE_NAME).then((cache) => cache.put(request, clone)).catch(() => undefined);
            }
            return networkResponse;
          })
          .catch(() => {
            // CRITICAL: NEVER return index.html for a failed JavaScript or CSS request.
            // Returning HTML for a .js chunk causes fatal "Unexpected token '<'" parse errors.
            const isJs = url.pathname.endsWith('.js') || request.destination === 'script';
            const isCss = url.pathname.endsWith('.css') || request.destination === 'style';

            if (isJs) {
              return new Response('/* [FocusFlow SW] Offline: JavaScript chunk unavailable */', {
                status: 503,
                statusText: 'Service Unavailable (Offline)',
                headers: { 'Content-Type': 'application/javascript; charset=utf-8' },
              });
            }

            if (isCss) {
              return new Response('/* [FocusFlow SW] Offline: CSS chunk unavailable */', {
                status: 503,
                statusText: 'Service Unavailable (Offline)',
                headers: { 'Content-Type': 'text/css; charset=utf-8' },
              });
            }

            return new Response('', { status: 504, statusText: 'Gateway Timeout (Offline)' });
          });
      })
    );
    return;
  }

  // 5. Static Shell Resources (icons, manifest, root images)
  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;

      return fetch(request)
        .then((response) => {
          if (response && response.status === 200 && response.type === 'basic') {
            const clone = response.clone();
            caches.open(SHELL_CACHE_NAME).then((cache) => cache.put(request, clone)).catch(() => undefined);
          }
          return response;
        })
        .catch(() => {
          return new Response('', { status: 504, statusText: 'Gateway Timeout' });
        });
    })
  );
});
